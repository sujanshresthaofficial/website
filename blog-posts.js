(function renderBlogPost() {
    const params = new URLSearchParams(window.location.search);
    const postId = params.get("post");
    const post = blogPosts[postId];
    const article = document.getElementById("blogArticle");

    if (!article) return;

    if (!post) {
        document.title = "Article Not Found | Sujan Shrestha";
        article.innerHTML = `<div class="blog-not-found">
        <h1>Article Not Found</h1>
        <p>This article may have been moved or removed.</p>
        <a class="blog-back" href="blog.html">← Back to Blog</a>
        </div>`;
        return;
    }

    document.title = `${post.title} | Sujan Shrestha`;
    const description = post.title + " — a post by Sujan Shrestha.";
    const metaDescription = document.querySelector('meta[name="description"]');
    if (metaDescription) metaDescription.setAttribute("content", description);

    article.innerHTML = `
        <div class="reader-top-actions">
            <a href="blog.html" class="blog-back">
            <i class="fa-solid fa-arrow-left"></i> Back to Blog</a>
            <button class="reader-share" type="button" id="shareBlog">
            <i class="fa-solid fa-share-nodes"></i> Share</button>
        </div>
        <header class="reader-header">
            <span class="reader-category">${post.category}</span>
            <h1>${post.title}</h1>
            <div class="reader-meta">
            <span><i class="fa-regular fa-calendar"></i> ${post.date}</span>
            <span><i class="fa-regular fa-clock"></i> ${post.readTime}</span></div>
        </header>
        ${post.image ? `<img class="reader-cover" src="${post.image}" alt="${post.title}" loading="eager">` : ""}
        <div class="reader-content">${post.content}</div>
        <footer class="reader-footer">
            <a href="blog.html" class="blog-back">
            <i class="fa-solid fa-arrow-left"></i> Back to all posts</a>
        </footer>` ;

    document.getElementById("shareBlog")?.addEventListener("click", async () => {
        const shareData = { title: post.title, text: post.title, url: window.location.href };
        try {
            if (navigator.share) await navigator.share(shareData);
            else if (navigator.clipboard) { await navigator.clipboard.writeText(window.location.href); alert("Article link copied!"); }
            else window.prompt("Copy this article link:", window.location.href);
        } catch (error) {
            if (error.name !== "AbortError") console.error("Sharing failed:", error);
        }
    });
})();
